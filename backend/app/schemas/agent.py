"""Schemas for invoking Gemini-powered agents."""
from __future__ import annotations

from pydantic import BaseModel, Field

from .snapshot import WebDocument


class GeminiAgentRequest(BaseModel):
    message: str = Field(..., description="Prompt or instruction for the Gemini agent")
    llm_mode: str = Field(
        default="cloud",
        description="LLM execution mode: cloud (Groq, or Gemini for query planning), local (Ollama/Qwen), or openrouter (OpenRouter gateway for every node)",
    )
    documents: list[WebDocument] | None = Field(
        default=None,
        description="Optional context documents to ground the response.",
    )


class GeminiAgentResponse(BaseModel):
    output: str = Field(..., description="Natural-language response generated by the agent")
